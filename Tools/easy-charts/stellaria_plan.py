# 227 BPM: the dense parts keep a quarter pulse but only one chord per bar (on the downbeat of every other bar)
# and no 8th pairs, so the chart stays around 4 notes per second.
for m in list(R):
    if R[m] == '=' or not (37 <= m <= 60 or 70 <= m <= 117): continue
    r = list(R[m].replace('x.x.', 'x...'))
    for i, ch in enumerate(r):
        if ch == 'c' and not (i == 0 and m % 2 == 0): r[i] = 'x'
    R[m] = ''.join(r)

def cells(**slots):
    row = ['.'] * 16
    for k, v in slots.items(): row[int(k[1:])] = v
    return row
